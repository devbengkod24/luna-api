"""File domain entity."""
from dataclasses import dataclass
from datetime import datetime


@dataclass
class File:
    """File domain entity."""

    filename: str
    size_bytes: int
    content_type: str
    storage_path: str
    status: str
    tags: list[str] | None = None
    indexed_at: datetime | None = None
    id: str | None = None  # Generated by persistence when None (create)
    created_at: datetime | None = None  # Set by persistence when None (create)
    updated_at: datetime | None = None  # Set by persistence when None (create)

